def get_questions(subject: str, count: int = 5):
    pool = QUESTION_BANK.get(subject, _GENERIC_PLACEHOLDER)
    if len(pool) < count:
        # если в банке мало вопросов - берём с повторами, чтобы тест не ломался
        pool = (pool * (count // len(pool) + 1))
    return random.sample(pool, k=min(count, len(pool)))


def score_test(questions, answers: dict) -> int:
    """answers: {question_index(str): selected_option_index(int)}"""
    if not questions:
        return 0
    correct_count = 0
    for i, q in enumerate(questions):
        selected = answers.get(str(i))
        if selected is not None and int(selected) == q["correct"]:
            correct_count += 1
    return round(correct_count / len(questions) * 100)
